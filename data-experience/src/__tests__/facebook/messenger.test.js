import { readFileSync } from 'fs'
import { resolve } from 'path'
import experience from '@hestia.ai/facebook'
import FileManager from '~/utils/file-manager'
import NodeFile from '~/utils/node-file'
import { getCustomPipelineFromBlock } from '~/utils/test-utils'

// Tests run in UTC (jest.global-setup.cjs): dates of HTML exports are read in UTC here

const { preprocessors, files, keepOnlyFiles } = experience.options
const samplesDir = resolve(__dirname, '../../../../packages/lib/data-samples')

const BLOCKS = ['messenger-overview', 'messenger-deleted-accounts', 'messenger-anomalies', 'messenger-ids']

async function run(inputFiles) {
  const fileManager = new FileManager(preprocessors, null, files, keepOnlyFiles)
  await fileManager.init(inputFiles)
  const outputs = {}
  for (const id of BLOCKS) {
    outputs[id] = await getCustomPipelineFromBlock(experience, id)({ fileManager })
  }
  return outputs
}

// pipeline output without the file paths of its rows
function withoutFiles(value) {
  return JSON.parse(JSON.stringify(value, (key, v) => (key === 'files' ? undefined : v)))
}

function sample(name) {
  return new NodeFile(name, readFileSync(resolve(samplesDir, name)))
}

const thread = (folder, name) => `your_facebook_activity/messages/${folder}/${name}`

function htmlPage(title, sections, owner = 'Sam Owner', generated = 'Generated by {owner} on') {
  return '<html><head><title>' + title + '</title></head><body><header><h1>' + title + '</h1>' +
    '<aside>' + generated.replace('{owner}', owner) + ' <time datetime="2026-10-14T15:23Z">x</time></aside></header>' +
    '<main>' + sections.join('') + '</main></body></html>'
}

const htmlMessage = (sender, content, date) =>
  `<section class="_a6-g"><h2>${sender}</h2><div>${content}</div><footer><div>${date}</div></footer></section>`

describe('facebook – Messenger tabs', () => {
  test('the JSON and HTML samples give the same results, except for flags only JSON has', async() => {
    const json = await run([sample('facebook-messenger.zip')])
    const html = await run([sample('facebook-messenger-html.zip')])

    const { jsonConversations, htmlConversations, ...overview } = json['messenger-overview'].items[0].summary
    expect(jsonConversations).toBe(8)
    expect(htmlConversations).toBe(0)
    expect(html['messenger-overview'].items[0].summary).toEqual({ ...overview, jsonConversations: 0, htmlConversations: 8 })
    expect(html['messenger-overview'].items[0].years).toEqual(json['messenger-overview'].items[0].years)
    expect(html['messenger-overview'].items[0].folders).toEqual(json['messenger-overview'].items[0].folders)
    // same rows, apart from the files they come from
    expect(withoutFiles(html['messenger-deleted-accounts'])).toEqual(withoutFiles(json['messenger-deleted-accounts']))
    expect(withoutFiles(html['messenger-ids'])).toEqual(withoutFiles(json['messenger-ids']))
    // JSON: message_1.json … message_N.json; HTML: one message_1.html per conversation
    expect(html['messenger-ids'].items.map(row => row.files)).toEqual(
      json['messenger-ids'].items.map(row => [row.files[0].replace(/\.json$/, '.html')])
    )
    expect(json['messenger-ids'].items.find(row => row.title === 'Emma Jones').files).toEqual([
      'your_facebook_activity/messages/inbox/emmajones_10102289880000063/message_1.json',
      'your_facebook_activity/messages/inbox/emmajones_10102289880000063/message_2.json'
    ])

    expect(json['messenger-anomalies'].items[0].summary).toMatchObject({ emptyJson: 1, unsent: 1, geoblocked: 1 })
    // HTML: the unsent message has no text, so it counts as empty; no unsent or geoblocked flags
    expect(html['messenger-anomalies'].items[0].summary).toMatchObject({ emptyHtml: 2, unsent: 0, geoblocked: 0 })
  })

  test('the sample covers the cases the tabs are about', async() => {
    const json = await run([sample('facebook-messenger.zip')])
    expect(json['messenger-overview'].items[0].summary).toMatchObject({
      conversations: 8,
      oneToOne: 7,
      groups: 1,
      messages: 31,
      sent: 11,
      received: 20
    })
    expect(json['messenger-deleted-accounts'].items[0].summary).toEqual({
      conversations: 8,
      affected: 2,
      oneToOne: 1,
      groups: 1,
      theirMessages: 5,
      theirMessagesWithText: 5,
      withTheirMessages: 2
    })
    expect(json['messenger-ids'].items.map(row => [row.id, row.category])).toEqual([
      ['5581460000', 'shortId'],
      ['1096618500000033', 'group'],
      ['10101989430000023', 'longId'],
      ['10102289880000013', 'longId'],
      ['10102289880000063', 'longId'],
      ['10102977430000073', 'longId'],
      ['10103379680000043', 'longId'],
      ['10104575190000053', 'longId']
    ])
  })

  test('merges the files of a JSON conversation', async() => {
    const chunk = messages => JSON.stringify({
      participants: [{ name: 'Ana' }, { name: 'Sam Owner' }],
      messages,
      title: 'Ana'
    })
    const outputs = await run([
      new NodeFile(`${thread('inbox', 'ana_123')}/message_1.json`, chunk([
        { sender_name: 'Ana', timestamp_ms: Date.UTC(2020, 1, 2), content: 'Café ?' }
      ])),
      new NodeFile(`${thread('inbox', 'ana_123')}/message_2.json`, chunk([
        { sender_name: 'Sam Owner', timestamp_ms: Date.UTC(2019, 0, 1), content: '' }
      ])),
      // the owner is the person in the most conversations
      new NodeFile(`${thread('inbox', 'bo_456')}/message_1.json`, JSON.stringify({
        participants: [{ name: 'Bo' }, { name: 'Sam Owner' }],
        messages: [{ sender_name: 'Bo', timestamp_ms: Date.UTC(2021, 0, 1), content: 'hi' }],
        title: 'Bo'
      }))
    ])
    expect(outputs['messenger-overview'].items[0].summary).toMatchObject({
      conversations: 2,
      messages: 3,
      sent: 1,
      received: 2,
      first: '2019-01-01T00:00:00.000Z',
      last: '2021-01-01T00:00:00.000Z'
    })
    expect(outputs['messenger-anomalies'].items[0].conversations).toEqual([
      expect.objectContaining({ id: '123', messages: 2, empty: 1, allEmpty: false })
    ])
  })

  test('reads HTML conversations: header, participants, dates, reactions and media', async() => {
    const group = htmlPage('Hikers', [
      '<section><h2>Participants: Sam Owner, Ana, Facebook user and Bo</h2></section>',
      '<section><h2>Group invite link: off</h2></section>',
      htmlMessage('Facebook user', '&lt;script&gt;alert(1)&lt;/script&gt;', 'Dec 31, 2015 11:59:59 pm'),
      htmlMessage('Ana', '<div><img src="your_facebook_activity/messages/inbox/hikers_789/photos/1.jpg" /></div>', 'Jan 01, 2016 12:00:01 am'),
      htmlMessage('Sam Owner', 'ok<div><ul><li><span>👍Ana</span></li></ul></div>', 'Jan 01, 2016 12:30:00 pm'),
      htmlMessage('Bo', '', 'not a date')
    ])
    const outputs = await run([new NodeFile(`${thread('inbox', 'hikers_789')}/message_1.html`, group)])

    expect(outputs['messenger-overview'].items[0].summary).toMatchObject({
      conversations: 1,
      groups: 1,
      messages: 4,
      sent: 1,
      first: '2015-12-31T23:59:59.000Z',
      last: '2016-01-01T12:30:00.000Z'
    })
    expect(outputs['messenger-deleted-accounts'].items[0].conversations).toEqual([
      expect.objectContaining({ title: 'Hikers', participants: 4, theirMessages: 1, theirMessagesWithText: 1 })
    ])
    // the photo-only message is not empty; the reaction is not text; Bo's message is empty
    expect(outputs['messenger-anomalies'].items[0].summary).toMatchObject({ emptyHtml: 1 })
  })

  test('reads the French HTML export, one-to-one conversations included', async() => {
    const page = htmlPage('Utilisateur(ice) Facebook', [
      htmlMessage('Utilisateur(ice) Facebook', 'Ai-je la bonne personne ?', 'août 26, 2008 6:18:15 pm'),
      htmlMessage('Sam Owner', 'Oui', 'déc 01, 2008 9:00:00 am')
    ], 'Sam Owner', 'Générée par {owner} le')
    const outputs = await run([new NodeFile(`${thread('inbox', 'utilisateuricefacebook_42')}/message_1.html`, page)])
    expect(outputs['messenger-overview'].items[0].summary).toMatchObject({
      oneToOne: 1,
      sent: 1,
      received: 1,
      first: '2008-08-26T18:18:15.000Z',
      last: '2008-12-01T09:00:00.000Z'
    })
    expect(outputs['messenger-deleted-accounts'].items[0].summary).toMatchObject({ affected: 1, theirMessages: 1 })
  })

  test('shows nothing, without error, for an export without Messenger', async() => {
    const outputs = await run([new NodeFile('ads_information/ad_preferences.json', '{}')])
    expect(outputs['messenger-overview'].items[0].summary.conversations).toBe(0)
    expect(outputs['messenger-ids'].items).toEqual([])
  })
})
